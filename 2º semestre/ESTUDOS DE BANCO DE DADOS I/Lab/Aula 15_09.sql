CREATE TABLE CLIENTES
(CPF_CLIENTE NUMBER(12) CONSTRAINT pk_CPF_CLIENTE PRIMARY KEY,
    NOME_CLIENTE VARCHAR2(40),
    ENDERECO_CLIENTE VARCHAR2(30),
    TELEFONE_CLIENTE VARCHAR2(15));
    
CREATE TABLE PRODUTO 
(ID_PRODUTO NUMBER(12) CONSTRAINT pk_ID_PRODUTO PRIMARY KEY,
    NOME_PRODUTO VARCHAR2(40),
    FABRICANTE_PRODUTO VARCHAR2(30),
    PRECO_PRODUTO NUMBER (10,2));
    
CREATE TABLE COMPRAS
(ID_COMPRAS NUMBER(12) CONSTRAINT pk_ID_COMPRAS PRIMARY KEY,
    DATA_COMPRA DATE,
    FORMA_PAGTO_COMPRAS VARCHAR2(30),
    CPF_CLIENTE_COMPRAS NUMBER (12),
    ID_PRODUTO_COMPRAS NUMBER (12),
    FOREIGN KEY ( CPF_CLIENTE_COMPRAS) REFERENCES CLIENTES (CPF_CLIENTE),
    FOREIGN KEY ( ID_PRODUTO_COMPRAS) REFERENCES PRODUTO (ID_PRODUTO));
    
